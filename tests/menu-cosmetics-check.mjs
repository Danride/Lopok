import { readFileSync } from 'node:fs';
import { strict as assert } from 'node:assert';
import vm from 'node:vm';
const html = readFileSync(new URL('../index.html', import.meta.url), 'utf8');
const main = readFileSync(new URL('../src/main.js', import.meta.url), 'utf8');
const css = readFileSync(new URL('../styles/main.css', import.meta.url), 'utf8');
const cosmeticsSource = readFileSync(new URL('../src/systems/cosmetics.js', import.meta.url), 'utf8');
const audioSource = readFileSync(new URL('../src/audio/audio.js', import.meta.url), 'utf8');
assert.doesNotMatch(html + main, /\balert\s*\(/, 'browser alert() must not be used');
for (const id of ['start-btn','skins-btn','scythes-btn','skin-modal','scythe-modal','skin-grid','scythe-grid','menu-wallet']) assert.match(html, new RegExp(`id="${id}"`));
assert.match(main, /function drawMenuScene\(\)/, 'menu must render animated wheat');
assert.match(main, /drawStalk\(w\.x, w\.y/, 'menu must reuse the game wheat stalk renderer');
assert.match(main, /function setupMenuUI\(\)/);
assert.match(main, /function renderSkinShop\(\)/);
assert.match(css, /\.skin-grid/);
assert.match(css, /#menu \{/);
const stored = new Map();
const windowStub = {};
const localStorageStub = { getItem: key => stored.get(key) ?? null, setItem: (key, value) => stored.set(key, value) };
vm.runInNewContext(cosmeticsSource, { window: windowStub, localStorage: localStorageStub, JSON, Math, Number, Boolean, Array, Object });
const api = windowStub.LopokCosmetics;
assert.equal(api.skins.length, 10);
assert.equal(api.getState().coins, 0);
assert.equal(api.unlockOrEquipSkin('copper').reason, 'coins');
api.addCoins(100);
assert.equal(api.unlockOrEquipSkin('copper').ok, true);
assert.equal(api.getState().selectedSkin, 'copper');
assert.equal(api.getState().coins, 35);
api.setScythe('hook'); api.setMuted(true); api.saveBest(1234);
assert.equal(api.getState().selectedScythe, 'hook');
assert.equal(api.getState().muted, true);
assert.equal(api.getState().bestScore, 1234);
assert.ok(stored.has('lopok.player.v2'), 'preferences must persist');
for (const method of ['ensure','click','cut','hit','hurt','kill','levelUp','dash','block','stun','pickup','death']) assert.match(audioSource, new RegExp(`\\b${method}\\s*\\(`), `${method} sound remains available`);
console.log('Menu, cosmetics, persistence and audio checks passed.');
